# ─────────────────────────────────────────────────────────────
# 7. COSINE ANNEALING LR — smooth decay, no premature collapse
#    v4 used ReduceLROnPlateau which dropped LR too early
# ─────────────────────────────────────────────────────────────
def cosine_lr(epoch):
    if epoch < WARMUP_EPOCHS:
        return BASE_LR * (epoch + 1) / WARMUP_EPOCHS
    progress = (epoch - WARMUP_EPOCHS) / (TOTAL_EPOCHS - WARMUP_EPOCHS)
    return MIN_LR + 0.5 * (BASE_LR - MIN_LR) * (1 + np.cos(np.pi * progress))

lr_scheduler = tf.keras.callbacks.LearningRateScheduler(cosine_lr, verbose=0)

