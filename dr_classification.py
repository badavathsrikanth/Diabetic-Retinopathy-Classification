def predict_single(img_path, use_tta=True):
    if not os.path.exists(img_path):
        print(f"Not found: {img_path}"); return
    img_bgr = cv2.imread(img_path)
    img_bgr = cv2.resize(img_bgr, (IMG_SIZE, IMG_SIZE))
    lab = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2LAB)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    lab[:, :, 0] = clahe.apply(lab[:, :, 0])
    img_bgr = cv2.cvtColor(lab, cv2.COLOR_LAB2BGR)
    img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    batch   = np.expand_dims(img_rgb.astype(np.float32), 0)

    if use_tta:
        all_p = [model.predict(next(tta_datagen.flow(batch, batch_size=1)), verbose=0)[0]
                 for _ in range(8)]
        probs = np.mean(all_p, axis=0)
    else:
        probs = model.predict(batch, verbose=0)[0]

    pred = int(np.argmax(probs))
    print(f"\n  Class     : {pred} — {LABEL_MAP[pred]}")
    print(f"  Confidence: {probs[pred]*100:.1f}%")
    print("  All probs :", {LABEL_MAP[i]: f"{p*100:.1f}%" for i,p in enumerate(probs)})
    plt.figure(figsize=(5,5)); plt.imshow(img_rgb)
    plt.title(f"{LABEL_MAP[pred]} ({probs[pred]*100:.1f}%)"); plt.axis('off'); plt.show()

