# 5. MIXUP GENERATOR
#    Blends pairs of images+labels to reduce overfitting
#    and improve calibration on small datasets.
# ─────────────────────────────────────────────────────────────
def mixup_generator(generator, alpha=0.3):
    while True:
        X1, y1 = next(generator)
        X2, y2 = next(generator)
        n   = min(len(X1), len(X2))
        X1, y1, X2, y2 = X1[:n], y1[:n], X2[:n], y2[:n]
        lam = np.random.beta(alpha, alpha, size=(n, 1, 1, 1)).astype(np.float32)
        X_mix = lam * X1 + (1 - lam) * X2
        y_mix = lam.reshape(n, 1) * y1 + (1 - lam.reshape(n, 1)) * y2
        yield X_mix, y_mix

